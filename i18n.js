  let lang = "ar";

  // t("js_turn", { team: "أ" }) → يعوّض {team}
  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.ar[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  const ATTRS = [
    ["i18nAria", "aria-label"],
    ["i18nTitle", "title"],
    ["i18nAlt", "alt"],
  ];

  function apply(l) {
    lang = DICT[l] ? l : "ar";
    const d = DICT[lang];
    document.documentElement.lang = lang;
    document.documentElement.dir = d.dir;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    ATTRS.forEach(([ds, attr]) => {
      document.querySelectorAll(`[data-${ds.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}]`).forEach((el) => {
        el.setAttribute(attr, t(el.dataset[ds]));
      });
    });
    document.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang } }));
    return lang;
  }

  return { t, apply, get lang() { return lang; } };
